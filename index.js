    async function downloadBookOffline(book, button) {
        const bookId = Number(book.id);
        if (!Number.isSafeInteger(bookId) || bookId <= 0 || offlineDownloads.has(bookId)) return;
        if (!navigator.onLine) {
            button.title = t('downloadBookMissing');
            return;
        }

        const controller = new AbortController();
        offlineDownloads.set(bookId, controller);
        button.disabled = false;
        button.textContent = t('downloadBookCancel');
        button.setAttribute('aria-label', `${t('downloadBookCancel')}: ${cleanBookText(book.title)}`);
        try {
            const partsUrl = `https://backend.ketabonline.com/api/v2/books/${bookId}/parts`;
            const partsPayload = await fetchJsonWithOfflineCache(partsUrl, { signal: controller.signal }, true);
            if (partsPayload.status !== true || !Array.isArray(partsPayload.data) || partsPayload.data.length === 0) {
                throw new Error('Book has no downloadable parts.');
            }
            const parts = partsPayload.data.filter(part =>
                Number.isSafeInteger(part.page_id) && Number.isSafeInteger(part.pages) && part.pages > 0
            );
            const totalPages = parts.reduce((total, part) => total + part.pages, 0);
            if (!parts.length || !Number.isSafeInteger(totalPages) || totalPages <= 0) {
                throw new Error('Book page details are invalid.');
            }
            let completedPages = 0;
            for (const part of parts) {
                const query = new URLSearchParams({ part: String(part.name), is_recursive: '1' });
                const indexUrl = `https://backend.ketabonline.com/api/v2/books/${bookId}/index?${query}`;
                const indexPayload = await fetchJsonWithOfflineCache(indexUrl, { signal: controller.signal }, true);
                if (indexPayload.status !== true || !Array.isArray(indexPayload.data)) {
                    throw new Error('Book table of contents is invalid.');
                }
                for (let pageOffset = 0; pageOffset < part.pages; pageOffset += 1) {
                    if (controller.signal.aborted) throw new DOMException('Download cancelled.', 'AbortError');
                    const pageId = part.page_id + pageOffset;
                    const pageUrl = `https://backend.ketabonline.com/api/v2/books/${bookId}/pages/${pageId}`;
                    const pagePayload = await fetchJsonWithOfflineCache(
                        pageUrl,
                        { signal: controller.signal },
                        true
                    );
                    if (!pagePayload || typeof pagePayload.content !== 'string') {
                        throw new Error(`Book page ${pageId} has no readable content.`);
                    }
                    completedPages += 1;
                    button.textContent = `${t('downloadBookProgress')} ${formatBookNumber(completedPages)}/${formatBookNumber(totalPages)}`;
                }
            }
            await writeOfflineResponse(`offline-book:${bookId}`, {
                complete: true,
                bookId,
                title: cleanBookText(book.title),
                totalPages,
                downloadedAt: Date.now()
            }, true);
            button.textContent = t('downloadBookDone');
            button.disabled = true;
            button.title = t('downloadBookDone');
            if (readerState?.bookId === bookId) {
                document.getElementById('bookReaderNote').textContent = t('downloadBookDone');
            }
        } catch (error) {
            if (error.name === 'AbortError') {
                button.textContent = t('downloadBookOffline');
                return;
            }
            console.error('Unable to download a book for offline reading.', error);
            button.textContent = t('downloadBookError');
            button.title = error.message;
            if (readerState?.bookId === bookId) {
                document.getElementById('bookReaderNote').textContent = t('downloadBookError');
            }
        } finally {
            offlineDownloads.delete(bookId);
        }
    }

    async function loadBooks(pageNumber = 1) {
        if (booksRequestController) booksRequestController.abort();
        const controller = new AbortController();
        booksRequestController = controller;
        booksCurrentPage = pageNumber;
        const resultsStatus = document.getElementById('bookResultsStatus');
        const list = document.getElementById('libraryBookList');
        const pagination = document.getElementById('bookPagination');
        resultsStatus.textContent = t('loadingBooks');
        list.replaceChildren();
        pagination.hidden = true;

        const [sortField, sortDirection] = document.getElementById('bookSortSelect').value.split(':');
        const query = new URLSearchParams({
            is_active: '1',
            is_deleted: '0',
            page: String(pageNumber),
            limit: String(booksPerPage),
            q: document.getElementById('bookSearchInput').value.trim(),
            scope: 'titles',
            sort_field: sortField,
            sort_direction: sortDirection
        });
        bookCategoryGroups[document.getElementById('bookCategoryFilter').value].forEach(categoryId => {
            query.append('categories[]', String(categoryId));
        });

        const requestUrl = `https://backend.ketabonline.com/api/v2/books?${query}`;
        if (!navigator.onLine) {
            const manifest = await readOfflineResponse('offline-catalog-manifest');
            if (manifest?.complete) {
                const offlineCatalog = await readOfflineCatalog();
                if (offlineCatalog) {
                    renderOfflineCatalog(offlineCatalog, pageNumber);
                    return;
                }
            }
        }
        try {
            let payload;
            let lastError;
            for (let attempt = 0; attempt < 3; attempt += 1) {
                try {
                    payload = await fetchJsonWithOfflineCache(requestUrl, { signal: controller.signal });
                    if (payload.status !== true || !Array.isArray(payload.data) || !payload.meta) {
                        throw new Error('Book catalog returned an invalid response.');
                    }
                    break;
                } catch (error) {
                    if (error.name === 'AbortError') throw error;
                    lastError = error;
                    if (!navigator.onLine || attempt === 2 || (error.message.startsWith('Request failed with status')
                        && !error.message.includes('429') && !error.message.match(/status 5\d\d/))) {
                        throw error;
                    }
                    await new Promise(resolve => setTimeout(resolve, 700 * (attempt + 1)));
                }
            }
            if (!payload) throw lastError || new Error('Book catalog returned no results.');
            cacheBooks(requestUrl, payload);
            renderBooks(payload);
            if (!navigator.onLine) resultsStatus.textContent = t('booksLoadCached');
        } catch (error) {
            if (error.name === 'AbortError') return;
            console.error('Unable to load the book catalog.', error);
            const cachedPayload = await readOfflineResponse(requestUrl) || getCachedBooks(requestUrl);
            let usingStarterBooks = false;
            if (cachedPayload) {
                renderBooks(cachedPayload);
                resultsStatus.textContent = t('booksLoadCached');
            } else {
                renderOfflineCatalog(starterBooks, pageNumber, 'booksLoadFallback');
                usingStarterBooks = true;
            }
            const retryButton = document.createElement('button');
            retryButton.type = 'button';
            retryButton.textContent = t('retry');
            retryButton.addEventListener('click', () => loadBooks(booksCurrentPage), { once: true });
            if (cachedPayload) {
                resultsStatus.replaceChildren(document.createTextNode(`${t('booksLoadCached')} `), retryButton);
            } else if (usingStarterBooks) {
                resultsStatus.replaceChildren(document.createTextNode(`${t('booksLoadFallback')} `), retryButton);
            } else {
                resultsStatus.replaceChildren(document.createTextNode(`${t('booksLoadError')} `), retryButton);
            }
        }
    }

