    async function downloadOfflineCatalog() {
        const button = document.getElementById('downloadCatalogButton');
        if (offlineCatalogDownloadController) {
            offlineCatalogDownloadController.abort();
            return;
        }
        if (!navigator.onLine) {
            button.title = t('downloadCatalogOffline');
            return;
        }
        const controller = new AbortController();
        offlineCatalogDownloadController = controller;
        button.disabled = false;
        button.textContent = t('downloadCatalogCancel');
        try {
            const query = new URLSearchParams({
                is_active: '1',
                is_deleted: '0',
                page: '1',
                limit: String(booksPerPage),
                q: '',
                scope: 'titles',
                sort_field: 'created_at',
                sort_direction: 'DESC'
            });
            bookCategoryGroups.all.forEach(categoryId => query.append('categories[]', String(categoryId)));
            const firstUrl = `https://backend.ketabonline.com/api/v2/books?${query}`;
            const firstPayload = await fetchJsonWithOfflineCache(firstUrl, { signal: controller.signal }, true);
            if (firstPayload.status !== true || !Array.isArray(firstPayload.data) || !firstPayload.meta
                || !Number.isSafeInteger(firstPayload.meta.last_page)
                || !Number.isSafeInteger(firstPayload.meta.total)) {
                throw new Error('The book catalog returned invalid pagination details.');
            }
            await writeOfflineResponse('offline-catalog-page:000001', firstPayload.data, true);
            const totalPages = firstPayload.meta.last_page;
            const totalBooks = firstPayload.meta.total;
            let downloadedBooks = firstPayload.data.length;
            button.textContent = `${t('downloadCatalogProgress')} ${formatBookNumber(1)}/${formatBookNumber(totalPages)}`;
            for (let pageNumber = 2; pageNumber <= totalPages; pageNumber += 1) {
                if (controller.signal.aborted) throw new DOMException('Download cancelled.', 'AbortError');
                const pageKey = `offline-catalog-page:${String(pageNumber).padStart(6, '0')}`;
                const cachedPage = await readOfflineResponse(pageKey);
                if (Array.isArray(cachedPage)) {
                    downloadedBooks += cachedPage.length;
                    button.textContent = `${t('downloadCatalogProgress')} ${formatBookNumber(pageNumber)}/${formatBookNumber(totalPages)}`;
                    continue;
                }
                const pageQuery = new URLSearchParams(query);
                pageQuery.set('page', String(pageNumber));
                const pageUrl = `https://backend.ketabonline.com/api/v2/books?${pageQuery}`;
                const payload = await fetchJsonWithOfflineCache(pageUrl, { signal: controller.signal }, true);
                if (payload.status !== true || !Array.isArray(payload.data)) {
                    throw new Error(`Catalog page ${pageNumber} is invalid.`);
                }
                await writeOfflineResponse(pageKey, payload.data, true);
                downloadedBooks += payload.data.length;
                button.textContent = `${t('downloadCatalogProgress')} ${formatBookNumber(pageNumber)}/${formatBookNumber(totalPages)}`;
            }
            if (downloadedBooks !== totalBooks) {
                throw new Error(`Catalog contains ${downloadedBooks} books, expected ${totalBooks}.`);
            }
            await writeOfflineResponse('offline-catalog-manifest', {
                complete: true,
                totalBooks,
                totalPages,
                downloadedAt: Date.now()
            }, true);
            button.disabled = true;
            button.textContent = t('downloadCatalogDone');
            button.title = t('downloadCatalogDone');
            if (currentPage === 'books') loadBooks(booksCurrentPage);
        } catch (error) {
            if (error.name === 'AbortError') {
                button.textContent = t('downloadCatalog');
                return;
            }
            console.error('Unable to download the full offline catalog.', error);
            button.disabled = !navigator.onLine;
            button.textContent = t('downloadCatalogError');
            button.title = `${t('booksLoadError')} ${error.message}`;
            document.getElementById('bookResultsStatus').textContent =
                `${t('downloadCatalogError')} ${error.message}`;
        } finally {
            offlineCatalogDownloadController = null;
            if (!button.disabled) setOfflineCatalogButtonState();
        }
    }

