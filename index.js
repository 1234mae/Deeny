    function handleContentAction(event) {
        const saveButton = event.target.closest('[data-save-section][data-save-index]');
        if (saveButton) {
            toggleSavedItem(saveButton.dataset.saveSection, Number(saveButton.dataset.saveIndex));
            return;
        }
        const repeatButton = event.target.closest('[data-repeat-index][data-repeat-section]');
        if (!repeatButton) return;
        const section = repeatButton.dataset.repeatSection;
        const index = Number(repeatButton.dataset.repeatIndex);
        if (!data[section] || !Number.isInteger(index) || index < 0 || index >= data[section].length) return;
        const item = data[section][index];
        const repeat = getDhikrRepeatCount(item);
        if (!Number.isInteger(repeat)) return;
        const sectionRepetitions = remainingRepetitions[section] || (remainingRepetitions[section] = {});
        const remaining = sectionRepetitions[index] ?? repeat;
        if (remaining > 0) {
            sectionRepetitions[index] = remaining - 1;
            if (currentPage === 'saved') renderSavedPage();
            else if (currentPage === 'section') renderCurrentContent();
        }
    }
