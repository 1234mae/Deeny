    function openOfflineDatabase() {
        if (!('indexedDB' in window)) {
            return Promise.reject(new Error('IndexedDB is not available in this browser.'));
        }
        if (!offlineDatabasePromise) {
            offlineDatabasePromise = new Promise((resolve, reject) => {
                const request = window.indexedDB.open('islamic-app-offline', 1);
                request.onupgradeneeded = () => {
                    if (!request.result.objectStoreNames.contains('api-responses')) {
                        request.result.createObjectStore('api-responses', { keyPath: 'key' });
                    }
                };
                request.onsuccess = () => resolve(request.result);
                request.onerror = () => reject(request.error || new Error('Could not open offline storage.'));
                request.onblocked = () => reject(new Error('Offline storage upgrade was blocked by another tab.'));
            }).catch(error => {
                offlineDatabasePromise = null;
                throw error;
            });
        }
        return offlineDatabasePromise;
    }

    async function readOfflineResponse(key) {
        try {
            const database = await openOfflineDatabase();
            return await new Promise((resolve, reject) => {
                const transaction = database.transaction('api-responses', 'readonly');
                const request = transaction.objectStore('api-responses').get(key);
                request.onsuccess = () => resolve(request.result ? request.result.value : null);
                request.onerror = () => reject(request.error || new Error('Could not read offline data.'));
                transaction.onabort = () => reject(transaction.error || new Error('Offline data read was aborted.'));
            });
        } catch (error) {
            console.error('Unable to read offline book data.', error);
            return null;
        }
    }

    async function writeOfflineResponse(key, value, required = false) {
        try {
            const database = await openOfflineDatabase();
            await new Promise((resolve, reject) => {
                const transaction = database.transaction('api-responses', 'readwrite');
                transaction.objectStore('api-responses').put({ key, value, savedAt: Date.now() });
                transaction.oncomplete = resolve;
                transaction.onerror = () => reject(transaction.error || new Error('Could not save offline data.'));
                transaction.onabort = () => reject(transaction.error || new Error('Offline data write was aborted.'));
            });
            return true;
        } catch (error) {
            console.error('Unable to save book data for offline reading.', error);
            if (required) throw error;
            return false;
        }
    }

    async function fetchJsonWithOfflineCache(url, options = {}, requireOfflineSave = false) {
        if (!navigator.onLine) {
            const cachedPayload = await readOfflineResponse(url);
            if (cachedPayload !== null) return cachedPayload;
            throw new Error('This data has not been saved for offline use.');
        }
        try {
            const response = await fetch(url, options);
            if (!response.ok) throw new Error(`Request failed with status ${response.status}.`);
            const payload = await response.json();
            await writeOfflineResponse(url, payload, requireOfflineSave);
            return payload;
        } catch (error) {
            if (error.name === 'AbortError') throw error;
            if (requireOfflineSave) throw error;
            const cachedPayload = await readOfflineResponse(url);
            if (cachedPayload !== null) return cachedPayload;
            throw error;
        }
    }

    async function readOfflineCatalog() {
        const manifest = await readOfflineResponse('offline-catalog-manifest');
        if (!manifest?.complete || !Number.isSafeInteger(manifest.totalBooks)) return null;
        try {
            const database = await openOfflineDatabase();
            const books = await new Promise((resolve, reject) => {
                const transaction = database.transaction('api-responses', 'readonly');
                const store = transaction.objectStore('api-responses');
                const range = IDBKeyRange.bound('offline-catalog-page:', 'offline-catalog-page:\uffff');
                const request = store.openCursor(range);
                const result = [];
                request.onsuccess = () => {
                    const cursor = request.result;
                    if (!cursor) return;
                    if (Array.isArray(cursor.value.value)) result.push(...cursor.value.value);
                    cursor.continue();
                };
                transaction.oncomplete = () => resolve(result);
                transaction.onerror = () => reject(transaction.error || new Error('Could not read offline catalog.'));
                transaction.onabort = () => reject(transaction.error || new Error('Offline catalog read was aborted.'));
            });
            return books.length === manifest.totalBooks ? books : null;
        } catch (error) {
            console.error('Unable to read the offline catalog.', error);
            return null;
        }
    }

    function renderOfflineCatalog(books, pageNumber, statusKey = 'booksLoadCached') {
        const categoryIds = bookCategoryGroups[document.getElementById('bookCategoryFilter').value];
        const query = document.getElementById('bookSearchInput').value.trim().toLocaleLowerCase();
        const [sortField, sortDirection] = document.getElementById('bookSortSelect').value.split(':');
        const filteredBooks = books.filter(book => {
            const title = cleanBookText(book.title).toLocaleLowerCase();
            const categories = Array.isArray(book.categories) ? book.categories : [];
            const matchesCategory = categories.some(category => categoryIds.includes(Number(category.id)));
            return matchesCategory && (!query || title.includes(query));
        });
        filteredBooks.sort((first, second) => {
            let comparison;
            if (sortField === 'pages_count') {
                comparison = (Number(first.pages_count) || 0) - (Number(second.pages_count) || 0);
            } else if (sortField === 'created_at') {
                comparison = (Date.parse(first.created_at) || 0) - (Date.parse(second.created_at) || 0);
            } else {
                comparison = cleanBookText(first.title).localeCompare(
                    cleanBookText(second.title),
                    currentLanguage === 'en' ? 'en' : 'ar'
                );
            }
            return sortDirection === 'DESC' ? -comparison : comparison;
        });
        const lastPage = Math.max(1, Math.ceil(filteredBooks.length / booksPerPage));
        const safePage = Math.min(Math.max(1, pageNumber), lastPage);
        const from = filteredBooks.length ? (safePage - 1) * booksPerPage + 1 : 0;
        const pageBooks = filteredBooks.slice(from - 1, from - 1 + booksPerPage);
        renderBooks({
            data: pageBooks,
            meta: {
                current_page: safePage,
                from,
                to: pageBooks.length ? from + pageBooks.length - 1 : 0,
                last_page: lastPage,
                total: filteredBooks.length
            }
        });
        document.getElementById('bookResultsStatus').textContent += ` — ${t(statusKey)}`;
    }

